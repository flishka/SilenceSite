-- HELPER FUNCTIONS FOR ROLES
create or replace function public.is_admin()
returns boolean security definer language sql stable as $$
    select exists (
        select 1 from public.profiles
        where id = auth.uid() and role = 'ADMIN'::user_role and banned = false
    );
$$;

-- PROFILES RLS
drop policy if exists "Read own profile or admin read all" on public.profiles;
create policy "Read own profile or admin read all" on public.profiles
    for select using (auth.uid() = id or public.is_admin());

drop policy if exists "Users can update own non-sensitive profile" on public.profiles;
create policy "Users can update own non-sensitive profile" on public.profiles
    for update using (auth.uid() = id)
    with check (
        auth.uid() = id and 
        role = (select role from public.profiles where id = auth.uid()) and
        banned = (select banned from public.profiles where id = auth.uid())
    );

