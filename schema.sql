create or replace function public.handle_new_user()
returns trigger security definer language plpgsql as $$
declare
    _username text;
    _role user_role := 'USER'::user_role;
begin
    _username := coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1));
    if _username = 'flqshka' then
        _role := 'ADMIN'::user_role;
    end if;

    insert into public.profiles (id, username, email, role, avatar_url, created_at)
    values (
        new.id,
        _username,
        coalesce(new.raw_user_meta_data->>'real_email', new.email),
        _role,
        'https://api.dicebear.com/7.x/bottts/svg?seed=' || _username,
        now()
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute procedure public.handle_new_user();

create or replace function public.audit_action_trigger()
returns trigger security definer language plpgsql as $$
declare
    _actor text := 'system';
    _user_id uuid := auth.uid();
begin
    if _user_id is not null then
        select username into _actor from public.profiles where id = _user_id;
        if _actor is null then
            _actor := _user_id::text;
        end if;
    end if;

    if tg_op = 'INSERT' then
        insert into public.audit_log (actor, action, target, payload)
        values (_actor, 'INSERT', tg_table_name, row_to_json(NEW));
    elsif tg_op = 'UPDATE' then
        insert into public.audit_log (actor, action, target, payload)
        values (_actor, 'UPDATE', tg_table_name, jsonb_build_object('old', row_to_json(OLD), 'new', row_to_json(NEW)));
    elsif tg_op = 'DELETE' then
        insert into public.audit_log (actor, action, target, payload)
        values (_actor, 'DELETE', tg_table_name, row_to_json(OLD));
    end if;
    return null;
end;
$$;

